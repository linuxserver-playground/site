import * as React from 'react';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import CopyButton from './CopyButton';

export interface QuickStartTab {
  key: string;
  label: string;
  /** The full snippet. */
  text: string;
  /** The snippet without optional settings; omit when there is no such variant. */
  textRequired?: string;
  /** What the snippet is, for the copy button and the <pre> label ("docker-compose.yml"). */
  aria: string;
  /** Where the hub serves this document, when it does. */
  source?: string;
}

interface Props {
  name: string;
  tabs: QuickStartTab[];
}

/**
 * Compose / docker run / Kubernetes / quadlet tabs with a "show optional settings" switch and copy buttons.
 * Server-rendered with the full snippets, so it reads fine before (or without) hydration.
 */
export default function QuickStart({ name, tabs }: Props) {
  const [optional, setOptional] = React.useState(true);
  const [active, setActive] = React.useState(tabs[0]?.key ?? '');
  const id = React.useId();
  const current = tabs.find((t) => t.key === active) ?? tabs[0];
  const hasOptional = !!current?.textRequired && current.textRequired !== current.text;
  const textFor = (t: QuickStartTab) => (optional || !t.textRequired ? t.text : t.textRequired);

  return (
    <Tabs value={active} onValueChange={setActive} className="gap-0">
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-border px-3 py-2">
        <TabsList aria-label={`Ways to run ${name}`} className="h-auto flex-wrap">
          {tabs.map((t) => (
            <TabsTrigger key={t.key} value={t.key}>
              {t.label}
            </TabsTrigger>
          ))}
        </TabsList>
        {hasOptional && (
          <label htmlFor={`${id}-opt`} className="flex cursor-pointer items-center gap-2 text-sm text-muted-foreground select-none">
            <input id={`${id}-opt`} type="checkbox" checked={optional} onChange={(e) => setOptional(e.target.checked)} className="size-4 accent-primary" />
            Include optional settings
          </label>
        )}
      </div>
      {tabs.map((t) => (
        <TabsContent key={t.key} value={t.key} className="relative">
          <pre className="max-h-[28rem] overflow-auto p-4 pr-14 font-mono text-[0.8125rem] leading-relaxed" tabIndex={0} aria-label={t.aria}>
            <code>{textFor(t)}</code>
          </pre>
          <CopyButton text={textFor(t)} label={`Copy ${t.aria}`} className="absolute top-2 right-2" variant="secondary" />
          {t.source && (
            <p className="border-t border-border px-4 py-2 font-mono text-[0.6875rem] text-muted-foreground">
              Generated by the hub:{' '}
              <a href={t.source} className="break-all underline underline-offset-4 decoration-[var(--raft-hair-strong)] hover:text-foreground hover:decoration-current">
                {t.source.replace(/^https?:\/\//, '')}
              </a>
            </p>
          )}
        </TabsContent>
      ))}
    </Tabs>
  );
}
